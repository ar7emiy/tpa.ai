def create_initial_state(claim_details: Optional[Dict[str, Any]] = None) -> ClaimState:
    """Create initial state for a new claim.

    Args:
        claim_details: Optional dictionary with initial claim information

    Returns:
        A ClaimState object with default values and any provided claim details
    """
    claim_id = str(uuid.uuid4()) #changed it back to uuid4
    timestamp = datetime.datetime.now().isoformat()
    current_date = datetime.datetime.now().date()

    # Format as ISO
    current_date_str = current_date.isoformat()

    # Create initial state
    initial_state = ClaimState(
        claim_id=claim_id,
        status="new",
        created_at=timestamp,
        updated_at=timestamp,
        messages=[],
        claimant_info={},
        employer_info={},
        medical_info={},
        verification_status={},
        decision_status={},
        payment_info={"payments": []},
        recovery_status={},
        conversations={
            "claimant": [],
            "employer": [],
            "medical": []
        },
        # Add time tracking fields
        simulation_current_date=current_date_str,
        last_check_in_date=current_date_str,
        next_check_in_date=None,  # Will be set after medical info is gathered
        estimated_recovery_days=None,  # Will be calculated from medical info
        check_in_count=0,
        total_expected_check_ins=5,
        had_setback=False,
        finished=False
    )

    # Update with any provided claim details
    if claim_details:
        for key, value in claim_details.items():
            if key in initial_state:
                initial_state[key] = value

    # Save the initial state to database
    save_claim_state(initial_state)

    return initial_state




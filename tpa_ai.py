def get_claim_history(claim_id: str) -> Dict:
    """Retrieve complete claim history from database."""
    conn = sqlite3.connect("claims.db")
    cursor = conn.cursor()

    print(f"Retrieving claim history for {claim_id}...")

    # Get claim details
    cursor.execute("""
        SELECT claimant_info, employer_info, medical_info,
               verification_status, decision_status, payment_info,
               recovery_status
        FROM claims
        WHERE claim_id = ?
    """, (claim_id,))
    claim_row = cursor.fetchone()

    if not claim_row:
        print(f"Warning: No claim found with ID {claim_id}")
        return {
            "claim_details": {},
            "conversations": {"claimant": [], "medical": [], "employer": []},
            "payments": []
        }

    # Get conversations
    cursor.execute("""
        SELECT stakeholder_type, conversation_text, extracted_data, timestamp
        FROM conversations
        WHERE claim_id = ?
        ORDER BY timestamp DESC
    """, (claim_id,))
    conversations = cursor.fetchall()
    print(f"Found {len(conversations)} conversation records")

    # Get payments - Fix query to match actual database schema
    cursor.execute("""
        SELECT amount, payment_type, payment_date, processed_by
        FROM payments
        WHERE claim_id = ?
        ORDER BY payment_date DESC
    """, (claim_id,))
    payments = cursor.fetchall()
    print(f"Found {len(payments)} payment records")

    conn.close()

    # Organize conversations by stakeholder
    organized_conversations = {
        "claimant": [],
        "medical": [],
        "employer": []
    }

    for conv in conversations:
        stakeholder_type, text, data, timestamp = conv
        if stakeholder_type in organized_conversations:
            try:
                extracted_data = json.loads(data) if data else {}
                organized_conversations[stakeholder_type].append({
                    "timestamp": timestamp,
                    "conversation_text": text,
                    "extracted_data": extracted_data
                })
            except json.JSONDecodeError:
                print(f"Warning: Could not parse JSON data for {stakeholder_type} conversation")
                organized_conversations[stakeholder_type].append({
                    "timestamp": timestamp,
                    "conversation_text": text,
                    "extracted_data": {}
                })

    # Parse claim details
    try:
        claim_details = {
            "claimant_info": json.loads(claim_row[0]) if claim_row[0] else {},
            "employer_info": json.loads(claim_row[1]) if claim_row[1] else {},
            "medical_info": json.loads(claim_row[2]) if claim_row[2] else {},
            "verification_status": json.loads(claim_row[3]) if claim_row[3] else {},
            "decision_status": json.loads(claim_row[4]) if claim_row[4] else {},
            "payment_info": json.loads(claim_row[5]) if claim_row[5] else {},
            "recovery_status": json.loads(claim_row[6]) if claim_row[6] else {}
        }
    except json.JSONDecodeError as e:
        print(f"Warning: JSON parse error in claim details: {e}")
        claim_details = {}

    return {
        "claim_details": claim_details,
        "conversations": organized_conversations,
        "payments": [
            {
                "amount": p[0],
                "type": p[1],
                "date": p[2],
                "processor": p[3]  # Changed from "notes" to "processor" to match the schema
            } for p in payments
        ]
    }




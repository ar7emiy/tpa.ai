def payment_processor(state: ClaimState) -> ClaimState:
    print(100* '-')
    print('Payment Processor initialized')
    print(f"Processing payment for claim {state['claim_id']}")
    print(f"Current claim status: {state['status']}")
    print(f"Decision status: {json.dumps(state.get('decision_status', {}), indent=2)}")

    llm = initialize_model()
    # tools = [process_payment]
    # llm_with_tools = llm.bind_tools(tools)

    if state["status"] == "payment" and state["decision_status"].get("approved", False):
        print("Claim is approved for payment - calculating amount")

        # Use LLM to calculate payment amount
        payment_prompt = f"""You are Jill, the Payment Processing Agent. Calculate the appropriate payment amount for this workers' compensation claim.

        Claim Details:
        - Medical Info: {json.dumps(state['medical_info'], indent=2)}
        - Previous Payments: {json.dumps(state['payment_info'].get('payments', []), indent=2)}

        Determine:
        1. Appropriate payment amount 
        2. Payment type (initial, recurring, final)
        3. Payment period
        4. Reasoning for the amount

        Provide your response in JSON format:
        {{
            "payment_amount": float,
            "payment_type": "string",
            "payment_period": "string",
            "reasoning": "string"
        }}
        """

        # Get payment calculation from LLM - don't print the response
        payment_response = llm.invoke(payment_prompt)

        try:
            # Extract payment details from LLM response (but don't print the parsed details)
            payment_json = json.loads(repair_json(payment_response.content))

            # Process payment
            payment = process_payment.invoke({
                "payment_amount": payment_json["payment_amount"],
                "payment_type": payment_json["payment_type"],
                "payment_period": payment_json["payment_period"],
                "notes": payment_json["reasoning"]
            })

            # Print the processed payment in markdown format
            print("\n## 💰 Processed Payment")
            print("```json")
            print(json.dumps(payment, indent=2))
            print("```")

            # Update payment info in state
            if "payments" not in state["payment_info"]:
                state["payment_info"]["payments"] = []
                print("Initializing payments array in state")

            state["payment_info"]["payments"].append(payment)
            state["payment_info"]["last_payment_date"] = payment["payment_date"]
            state["payment_info"]["total_paid"] = sum(p["payment_amount"] for p in state["payment_info"]["payments"])

            print(f"\nTotal payments made: ${state['payment_info']['total_paid']:.2f}")

            # Save payment to database
            save_payment(state["claim_id"], payment)
            print("Payment saved to database")

            # Move to recovery check status
            print("Changing status from 'payment' to 'recovery_check'")
            state["status"] = "recovery_check"

        except Exception as e:
            print(f"Error processing payment: {e}")
            # Fallback to fixed amount if LLM parsing fails
            print("Using fallback payment amount")
            payment = process_payment.invoke({
                "payment_amount": 1000.00,
                "payment_type": "recurring",
                "payment_period": "Two weeks",
                "notes": "Standard payment (fallback amount)"
            })

            # Print the fallback payment in markdown format
            print("\n## 💰 Fallback Payment")
            print("```json")
            print(json.dumps(payment, indent=2))
            print("```")

            state["payment_info"]["payments"].append(payment)

            # Save fallback payment to database
            save_payment(state["claim_id"], payment)
            print("Fallback payment saved to database")

            print("Changing status from 'payment' to 'recovery_check'")
            state["status"] = "recovery_check"
    else:
        print(f"WARNING: Payment processor called with status '{state['status']}' and approved={state['decision_status'].get('approved', False)}")
        print("No payment will be processed - keeping current status")

    state["updated_at"] = datetime.datetime.now().isoformat()
    save_claim_state(state)
    print(f"Final payment processor status: {state['status']}")
    return state



def handle_setback(state):
    """Handle a recovery setback.

    Args:
        state: The current claim state

    Returns:
        Updated state with setback applied
    """
    # Track that a setback occurred
    state["had_setback"] = True

    # Decrement recovery stage by setting check-in count back
    if state.get("check_in_count", 0) > 1:
        state["check_in_count"] = max(1, state.get("check_in_count", 0) - 1)

    # Extend estimated recovery time
    if state.get("estimated_recovery_days"):
        extension_days = 14  # Add two weeks to recovery time
        state["estimated_recovery_days"] += extension_days

        # Update next check-in date to be sooner (7 days from now)
        current_date = datetime.date.fromisoformat(state["simulation_current_date"])
        next_check_in = current_date + datetime.timedelta(days=7)
        state["next_check_in_date"] = next_check_in.isoformat()

        print(f"🚨 SETBACK DETECTED: Recovery extended by {extension_days} days")
        print(f"New estimated recovery days: {state['estimated_recovery_days']}")
        print(f"Next check-in moved up to: {state['next_check_in_date']}")

    return state

def advance_simulation_time(state: ClaimState, days: int = 1) -> ClaimState:
    """Advance the simulation time by specified number of days."""
    if not state.get("simulation_current_date"):
        print("Warning: simulation_current_date not found in state, initializing to today")
        state["simulation_current_date"] = datetime.datetime.now().date().isoformat()

    current_date = datetime.date.fromisoformat(state["simulation_current_date"])
    new_date = current_date + datetime.timedelta(days=days)
    state["simulation_current_date"] = new_date.isoformat()

    print(f"Advanced simulation time to {state['simulation_current_date']}")
    return state

def print_weekly_progress(state: ClaimState) -> None:
    """Print weekly progress information."""
    current_date = datetime.date.fromisoformat(state["simulation_current_date"])
    week_start = current_date - datetime.timedelta(days=current_date.weekday())
    week_end = week_start + datetime.timedelta(days=6)

    print("\n" + "=" * 50)
    print(f"WEEK: {week_start.isoformat()} to {week_end.isoformat()}")
    print(f"Claim ID: {state['claim_id']}")
    print(f"Current Status: {state['status']}")

    if state.get("recovery_status"):
        print(f"Recovery Progress: {state['recovery_status'].get('recovery_status', 'Unknown')}")
        print(f"Work Status: {state['recovery_status'].get('work_status', 'Unknown')}")

    if state.get("next_check_in_date"):
        print(f"Next Check-in: {state['next_check_in_date']}")

    print("=" * 50 + "\n")

def get_previous_diagnoses() -> List[str]:
    """
    Get all previous diagnoses from the claims database to avoid repeating them.

    Returns:
        List of previous diagnoses as strings
    """
    try:
        # Try to connect to the database
        conn = sqlite3.connect("claims.db")
        cursor = conn.cursor()

        # Query all medical info from the claims table
        cursor.execute("SELECT medical_info FROM claims WHERE medical_info IS NOT NULL")
        results = cursor.fetchall()
        conn.close()

        # Extract diagnoses from the results
        diagnoses = []
        for result in results:
            try:
                medical_info = json.loads(result[0]) if result[0] else {}
                if medical_info and "diagnosis" in medical_info and medical_info["diagnosis"]:
                    diagnoses.append(medical_info["diagnosis"])
            except json.JSONDecodeError:
                print(f"Warning: Could not parse JSON medical data in database")

        return diagnoses
    except Exception as e:
        print(f"Error retrieving previous diagnoses: {e}")
        # If something goes wrong, initialize the database and return empty list
        initialize_database()
        return []





















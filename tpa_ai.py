def create_workflow():
    """Create the LangGraph workflow for claims processing.

    Returns:
        A compiled LangGraph StateGraph
    """
    print(100* '-')
    print('Workflow initialized')
    # Initialize graph
    graph_builder = StateGraph(ClaimState)
    print(graph_builder)

    # Add agent nodes
    graph_builder.add_node("intake", intake_agent)
    graph_builder.add_node("adjuster", claims_adjuster)
    graph_builder.add_node("payment", payment_processor)
    graph_builder.add_node("consolidated_recovery", consolidated_recovery_check_agent)

    # Define routing
    graph_builder.add_edge(START, "intake")
    graph_builder.add_conditional_edges("intake", route_after_intake)
    graph_builder.add_conditional_edges("adjuster", route_after_adjuster)
    graph_builder.add_conditional_edges("payment", route_after_payment)
    graph_builder.add_conditional_edges("consolidated_recovery", route_after_consolidated_recovery)

    # Compile the graph
    return graph_builder.compile()


# Execution functions
def process_claim(initial_state):
    """Process a claim through the workflow.

    Args:
        initial_state: The initial claim state

    Returns:
        Final state after processing, or a state with status "needs_human_handler" if recursion limit is reached
    """
    # Create workflow
    workflow = create_workflow()

    # Set recursion limit to allow for loops in the workflow
    config = {"recursion_limit": 40}

    # Process the claim
    try:
        result = workflow.invoke(initial_state, config)
        return result
    except Exception as e:
        # Check if it's a recursion error
        if "Recursion limit" in str(e):
            print(f"Recursion limit reached for claim {initial_state['claim_id']}.")
            # Update the state to indicate it needs human handling
            initial_state["status"] = "needs_human_handler"
            initial_state["updated_at"] = datetime.datetime.now().isoformat()
            # Save this status to the database
            save_claim_state(initial_state)
            return initial_state
        else:
            # Re-raise other exceptions
            raise







